-- Computer Repair Appointment and Service Management System (CRSM)
-- Fresh Supabase project setup. Run this once in the Supabase SQL Editor.
-- This is non-destructive: it does not drop or overwrite existing business tables.
-- No sample records are inserted.

begin;

-- ---------------------------------------------------------------------------
-- Business data: PostgreSQL version of docs/create_tables.sql + constraints.sql
-- Table names are unquoted so PostgreSQL stores lowercase names. The Java DAO's
-- unquoted mixed-case references resolve to the same lowercase names.
-- ---------------------------------------------------------------------------

create table if not exists public.customers (
    customer_id integer generated by default as identity primary key,
    customer_name varchar(100) not null,
    contact_number varchar(20) not null,
    email varchar(100),
    address varchar(255)
);

create table if not exists public.computers (
    computer_id integer generated by default as identity primary key,
    customer_id integer not null references public.customers(customer_id)
        on update cascade on delete restrict,
    device_type varchar(50) not null,
    brand varchar(50) not null,
    model varchar(100),
    serial_number varchar(100),
    reported_problem text
);

create table if not exists public.technicians (
    technician_id integer generated by default as identity primary key,
    technician_name varchar(100) not null,
    contact_number varchar(20),
    specialization varchar(100),
    availability varchar(50)
);

create table if not exists public.repair_services (
    service_id integer generated by default as identity primary key,
    service_name varchar(100) not null,
    description text,
    service_price numeric(10,2) not null,
    constraint chk_service_price_nonnegative check (service_price >= 0)
);

create table if not exists public.appointments (
    appointment_id integer generated by default as identity primary key,
    customer_id integer not null references public.customers(customer_id)
        on update cascade on delete restrict,
    computer_id integer not null references public.computers(computer_id)
        on update cascade on delete restrict,
    appointment_date date not null,
    appointment_time time not null,
    purpose varchar(255),
    appointment_status varchar(50) not null,
    constraint chk_appointment_status_allowed check (appointment_status in ('Pending', 'Confirmed', 'Completed', 'Cancelled'))
);

create table if not exists public.repair_requests (
    repair_request_id integer generated by default as identity primary key,
    computer_id integer not null references public.computers(computer_id)
        on update cascade on delete restrict,
    technician_id integer references public.technicians(technician_id)
        on update cascade on delete set null,
    service_id integer references public.repair_services(service_id)
        on update cascade on delete set null,
    reported_problem text not null,
    diagnosis text,
    repair_status varchar(50) not null,
    estimated_cost numeric(10,2),
    final_cost numeric(10,2),
    constraint chk_repair_status_allowed check (repair_status in (
        'Pending', 'Confirmed', 'Under Diagnosis', 'Under Repair',
        'Waiting for Parts', 'Ready for Pickup', 'Completed'
    )),
    constraint chk_estimated_cost_nonnegative check (estimated_cost is null or estimated_cost >= 0),
    constraint chk_final_cost_nonnegative check (final_cost is null or final_cost >= 0)
);

create table if not exists public.payments (
    payment_id integer generated by default as identity primary key,
    repair_request_id integer not null references public.repair_requests(repair_request_id)
        on update cascade on delete restrict,
    amount_paid numeric(10,2) not null,
    payment_date date not null,
    payment_status varchar(50) not null,
    constraint chk_payment_status_allowed check (payment_status in ('Unpaid', 'Partial', 'Paid')),
    constraint chk_amount_paid_nonnegative check (amount_paid >= 0)
);

-- Reporting views ported from docs/Repairs_&_Views.sql.
create or replace view public.active_repair_status as
select r.repair_request_id, c.customer_name, comp.device_type, comp.brand, comp.model,
       t.technician_name, r.repair_status, r.estimated_cost, r.final_cost
from public.repair_requests r
join public.computers comp on r.computer_id = comp.computer_id
join public.customers c on comp.customer_id = c.customer_id
left join public.technicians t on r.technician_id = t.technician_id
where r.repair_status <> 'Completed';

create or replace view public.appointment_schedule as
select a.appointment_id, a.appointment_date, a.appointment_time, c.customer_name,
       comp.device_type, comp.brand, comp.model, a.purpose, a.appointment_status
from public.appointments a
join public.customers c on a.customer_id = c.customer_id
join public.computers comp on a.computer_id = comp.computer_id;

create or replace view public.repair_history as
select c.customer_id, c.customer_name, comp.computer_id, comp.brand, comp.model,
       r.repair_request_id, r.reported_problem, r.diagnosis, r.repair_status,
       r.estimated_cost, r.final_cost
from public.customers c
join public.computers comp on c.customer_id = comp.customer_id
join public.repair_requests r on comp.computer_id = r.computer_id;

create or replace view public.technician_workload as
select t.technician_id, t.technician_name, t.specialization, t.availability,
       count(r.repair_request_id) as total_repairs
from public.technicians t
left join public.repair_requests r on t.technician_id = r.technician_id
group by t.technician_id, t.technician_name, t.specialization, t.availability;

create or replace view public.repair_revenue as
select r.repair_request_id, c.customer_name, comp.brand, comp.model, rs.service_name,
       r.final_cost, coalesce(sum(p.amount_paid), 0) as total_paid,
       r.final_cost - coalesce(sum(p.amount_paid), 0) as remaining_balance
from public.repair_requests r
join public.computers comp on r.computer_id = comp.computer_id
join public.customers c on comp.customer_id = c.customer_id
left join public.repair_services rs on r.service_id = rs.service_id
left join public.payments p on r.repair_request_id = p.repair_request_id
group by r.repair_request_id, c.customer_name, comp.brand, comp.model, rs.service_name, r.final_cost;

create or replace view public.pending_repairs as
select r.repair_request_id, c.customer_name, comp.brand, comp.model, t.technician_name,
       r.repair_status, r.estimated_cost, r.final_cost
from public.repair_requests r
join public.computers comp on r.computer_id = comp.computer_id
join public.customers c on comp.customer_id = c.customer_id
left join public.technicians t on r.technician_id = t.technician_id
where r.repair_status in ('Pending', 'Confirmed', 'Under Diagnosis', 'Under Repair', 'Waiting for Parts', 'Ready for Pickup');

create or replace view public.most_requested_services as
select rs.service_id, rs.service_name, rs.service_price, count(r.repair_request_id) as times_requested
from public.repair_services rs
left join public.repair_requests r on rs.service_id = r.service_id
group by rs.service_id, rs.service_name, rs.service_price;

-- Views are invoked with the caller's privileges so base-table RLS applies.
alter view public.active_repair_status set (security_invoker = true);
alter view public.appointment_schedule set (security_invoker = true);
alter view public.repair_history set (security_invoker = true);
alter view public.technician_workload set (security_invoker = true);
alter view public.repair_revenue set (security_invoker = true);
alter view public.pending_repairs set (security_invoker = true);
alter view public.most_requested_services set (security_invoker = true);

-- Realtime availability: authenticated Staff/Admin subscribers may read
-- technician rows. The Java subscription requests only id, name and availability.
alter table public.technicians enable row level security;
revoke all on table public.technicians from anon, authenticated;
grant select on table public.technicians to authenticated;

-- ---------------------------------------------------------------------------
-- Supabase Auth profiles and Customer-first signup.
-- Signup form contains no role control; the trigger explicitly stores CUSTOMER.
-- The legacy Customers table requires a contact number, which signup does not
-- collect, so account-to-customer mapping remains a separate confirmed workflow.
-- ---------------------------------------------------------------------------

create table if not exists public.crsm_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text not null unique,
    full_name text not null,
    username text not null unique,
    role text not null default 'CUSTOMER' check (role in ('CUSTOMER', 'STAFF', 'ADMIN')),
    avatar_path text,
    created_at timestamptz not null default now()
);

create table if not exists public.crsm_settings (
    setting_key text primary key,
    setting_value text,
    updated_at timestamptz not null default now()
);

create schema if not exists private;
revoke all on schema private from public;
revoke all on schema private from anon;
grant usage on schema private to authenticated;

create or replace function private.current_crsm_role()
returns text language sql stable security definer set search_path = ''
as $$ select p.role from public.crsm_profiles p where p.id = auth.uid() $$;

create or replace function private.is_crsm_admin()
returns boolean language sql stable security definer set search_path = ''
as $$ select coalesce(private.current_crsm_role() = 'ADMIN', false) $$;

revoke all on function private.current_crsm_role() from public, anon;
revoke all on function private.is_crsm_admin() from public, anon;
grant execute on function private.current_crsm_role() to authenticated;
grant execute on function private.is_crsm_admin() to authenticated;

drop policy if exists crsm_technicians_read_staff_admin on public.technicians;
create policy crsm_technicians_read_staff_admin on public.technicians
    for select to authenticated
    using (private.current_crsm_role() in ('STAFF', 'ADMIN'));

create or replace function private.create_crsm_profile_for_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
    insert into public.crsm_profiles (id, email, full_name, username, role)
    values (
        new.id,
        new.email,
        coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), split_part(new.email, '@', 1)),
        coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(new.email, '@', 1) || '_' || left(new.id::text, 8)),
        'CUSTOMER'
    );
    return new;
end;
$$;

drop trigger if exists crsm_create_profile_after_signup on auth.users;
create trigger crsm_create_profile_after_signup after insert on auth.users
for each row execute procedure private.create_crsm_profile_for_new_user();
revoke all on function private.create_crsm_profile_for_new_user() from public, anon, authenticated;

create or replace function public.promote_crsm_user(target_user uuid, target_role text)
returns void language plpgsql security invoker set search_path = ''
as $$
begin
    if not private.is_crsm_admin() then raise exception 'Only an administrator may promote accounts'; end if;
    if target_role not in ('STAFF', 'ADMIN') then raise exception 'Promotion role must be STAFF or ADMIN'; end if;
    update public.crsm_profiles set role = target_role where id = target_user;
    if not found then raise exception 'Target account was not found'; end if;
end;
$$;

create or replace function public.set_crsm_business_logo(logo_path text)
returns void language plpgsql security invoker set search_path = ''
as $$
begin
    if not private.is_crsm_admin() then raise exception 'Only an administrator may change the business logo'; end if;
    insert into public.crsm_settings (setting_key, setting_value, updated_at)
    values ('business_logo_path', logo_path, now())
    on conflict (setting_key) do update set setting_value = excluded.setting_value, updated_at = now();
end;
$$;

alter table public.crsm_profiles enable row level security;
alter table public.crsm_settings enable row level security;

drop policy if exists crsm_profiles_read_self_or_admin on public.crsm_profiles;
create policy crsm_profiles_read_self_or_admin on public.crsm_profiles for select to authenticated
using (id = auth.uid() or private.is_crsm_admin());

drop policy if exists crsm_profiles_update_self on public.crsm_profiles;
create policy crsm_profiles_update_self on public.crsm_profiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid() and role = private.current_crsm_role());

drop policy if exists crsm_profiles_admin_update on public.crsm_profiles;
create policy crsm_profiles_admin_update on public.crsm_profiles for update to authenticated
using (private.is_crsm_admin()) with check (private.is_crsm_admin());

drop policy if exists crsm_settings_read_authenticated on public.crsm_settings;
create policy crsm_settings_read_authenticated on public.crsm_settings for select to authenticated using (true);
drop policy if exists crsm_settings_admin_insert on public.crsm_settings;
create policy crsm_settings_admin_insert on public.crsm_settings for insert to authenticated
with check (private.is_crsm_admin());
drop policy if exists crsm_settings_admin_update on public.crsm_settings;
create policy crsm_settings_admin_update on public.crsm_settings for update to authenticated
using (private.is_crsm_admin()) with check (private.is_crsm_admin());

revoke all on public.crsm_profiles from anon;
grant select, update on public.crsm_profiles to authenticated;
revoke all on public.crsm_settings from anon;
grant select, insert, update on public.crsm_settings to authenticated;
revoke execute on function public.promote_crsm_user(uuid, text) from public, anon, authenticated;
grant execute on function public.promote_crsm_user(uuid, text) to authenticated;
revoke execute on function public.set_crsm_business_logo(text) from public, anon, authenticated;
grant execute on function public.set_crsm_business_logo(text) to authenticated;

