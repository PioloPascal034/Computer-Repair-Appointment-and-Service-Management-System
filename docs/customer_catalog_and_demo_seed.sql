create table if not exists public.crsm_device_catalog (
  device_id bigint generated by default as identity primary key,
  device_type text not null,
  brand text not null,
  model text not null,
  specification text,
  release_year smallint,
  constraint crsm_device_catalog_unique unique(device_type,brand,model)
);
create table if not exists public.repair_service_device_prices (
  service_id integer not null references public.repair_services(service_id) on delete cascade,
  device_type text not null,
  service_price numeric(10,2) not null check(service_price>=0),
  primary key(service_id,device_type)
);
